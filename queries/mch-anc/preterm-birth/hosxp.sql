--   1) @start_date, @end_date : ช่วงปีงบประมาณที่ต้องการ
--   2) (ทางเลือก) filter ward/spclty ของห้องคลอด ถ้าต้องการจำกัดเฉพาะบางแผนก
--   3) รูปแบบการเก็บ icd10 (มีจุด/ไม่มีจุด) : query จัดการให้แล้วด้วย REPLACE
-- ข้อจำกัด     :
--   1) พึ่งความครบถ้วนของการลงรหัส O80-O84 และ O60.1
--      ถ้า coder ไม่ลง O60.1 ตัวตั้งจะต่ำกว่าความเป็นจริง
--   2) นับเฉพาะการคลอดในโรงพยาบาลนี้
--   3) ไม่แยก livebirth/stillbirth ด้วยรหัสชุดนี้
--   4) ใช้ตรวจสอบภายในเท่านั้น ค่าทางการอ้างอิงจากระบบ HDC
-- ============================================================

-- หมายเหตุสำคัญ: โรงพยาบาลที่บันทึกอายุครรภ์ตอนคลอด (GA) ในระบบห้องคลอดของ HOSxP
-- สามารถคำนวณจากอายุครรภ์ได้ตรงกว่าการใช้รหัส ICD-10
-- แต่ชื่อตารางห้องคลอดต่างกันตามรุ่น (v3/XE) จึงไม่รวมไว้ใน query กลางนี้
-- หากโรงพยาบาลของท่านมีตารางดังกล่าว เชิญแบ่งปัน version ของท่านผ่าน issue "แบ่งปัน Query"

-- ============================================================
-- พารามิเตอร์ (แก้ค่าที่นี่ที่เดียว ไม่ต้องไล่แก้ใน query)
-- ============================================================

SET @start_date := '2025-10-01';  -- ปีงบประมาณ 2569 : เริ่ม 1 ต.ค. 2568
SET @end_date   := '2026-09-30';  -- ปีงบประมาณ 2569 : สิ้นสุด 30 ก.ย. 2569

-- ============================================================
-- 1) Query สรุป (ตัวตั้ง/ตัวหาร/ร้อยละ)
-- ============================================================
-- ตัวหาร : จำนวน admission ที่มีรหัสการคลอด O80-O84 ใน iptdiag
--          และจำหน่าย (dchdate) ในช่วงเวลาที่กำหนด
--          นับเป็นราย admission (an) : หนึ่งการคลอดต่อหนึ่งแม่ต่อหนึ่ง admission
--          ครรภ์แฝดจึงนับครั้งเดียว
-- ตัวตั้ง : admission ในตัวหารที่มีรหัส O60.1
--          (preterm labour with preterm delivery : เจ็บครรภ์ก่อนกำหนดและคลอดก่อนกำหนด)
-- เหตุผลที่ไม่จำกัด diagtype = '1' (principal diagnosis) :
--   รหัสการคลอดและรหัส O60.1 อาจถูกลงเป็นการวินิจฉัยรองเมื่อการวินิจฉัยหลัก
--   เป็นภาวะแทรกซ้อนอื่น การจำกัดเฉพาะ diagtype = '1' จะทำให้นับตกหล่น
-- เหตุผลที่ใช้ dchdate : การลงรหัสสรุปโรคของ IPD จะครบถ้วนเมื่อจำหน่ายแล้ว
--   และ BETWEEN จะตัดผู้ป่วยที่ยังไม่จำหน่าย (dchdate เป็น NULL) ออกให้เอง
-- หมายเหตุ: ผลจาก query นี้ใช้ตรวจสอบภายในเท่านั้น ค่าทางการอ้างอิงจากระบบ HDC

-- โครงสร้างภายใน: t มีหนึ่งแถวต่อหนึ่ง an เสมอ (ipt.an เป็น key และตรวจรหัสด้วย EXISTS ไม่ใช่ JOIN)
-- ห้ามเปลี่ยน EXISTS เป็น JOIN iptdiag โดยตรง เพราะจะได้หลายแถวต่อ an แล้วตัวเลขเกินจริง
-- ใช้ COUNT(DISTINCT t.an) ไว้เป็นเกราะอีกชั้น เผื่อมีการแก้โครงสร้างในอนาคต

SELECT
    COUNT(DISTINCT t.an)              AS `จำนวนการคลอดทั้งหมด (ตัวหาร)`,
    IFNULL(SUM(t.preterm_flag), 0)    AS `จำนวนคลอดก่อนกำหนดตามรหัส O60.1 (ตัวตั้ง)`,
    ROUND(IFNULL(SUM(t.preterm_flag), 0) * 100.0
          / NULLIF(COUNT(DISTINCT t.an), 0), 2)   AS `ร้อยละ`
FROM (
    SELECT
        i.an,
        CASE WHEN EXISTS (
                 SELECT 1
                 FROM iptdiag dx2
                 WHERE dx2.an = i.an
                   -- REPLACE กันทั้งกรณีเก็บ O601 และ O60.1
                   AND REPLACE(dx2.icd10, '.', '') LIKE 'O601%'
             )
             THEN 1 ELSE 0 END AS preterm_flag
    FROM ipt i
    WHERE i.dchdate BETWEEN @start_date AND @end_date
      -- AND i.ward = '00'      -- [ปรับตามโรงพยาบาล] (ทางเลือก) จำกัดเฉพาะ ward ห้องคลอด
      --                        -- ปกติไม่จำเป็น เพราะกรองด้วยรหัส O80-O84 อยู่แล้ว
      AND EXISTS (
              SELECT 1
              FROM iptdiag dx1
              WHERE dx1.an = i.an
                -- รหัสการคลอด O80 ถึง O84 (match แบบไม่สนใจจุด)
                AND REPLACE(dx1.icd10, '.', '') REGEXP '^O8[0-4]'
          )
) t;

-- ============================================================
-- 2) Query รายละเอียดราย admission (ใช้ภายใน ห้ามแชร์)
-- ============================================================
-- คำเตือน: ผลรายบุคคลมีข้อมูลส่วนบุคคลของผู้ป่วย
--          ใช้ตรวจสอบภายในโรงพยาบาลเท่านั้น ห้ามแชร์ออกนอกโรงพยาบาล
--          (ดู docs/data-privacy.md)
-- เงื่อนไขการนับตรงกับ Query 1 ทุกประการ ใช้ไล่ตรวจว่า admission ใด
-- ถูกนับในตัวหาร และรายใดพบ/ไม่พบรหัส O60.1
-- ระหว่างพัฒนา แนะนำเติม LIMIT 100 ท้าย query เพื่อลดภาระฐานข้อมูล

SELECT
    i.an,
    i.hn,
    i.regdate                          AS `วันรับไว้`,
    i.dchdate                          AS `วันจำหน่าย`,
    CASE WHEN EXISTS (
             SELECT 1
             FROM iptdiag dx2
             WHERE dx2.an = i.an
               AND REPLACE(dx2.icd10, '.', '') LIKE 'O601%'
         )
         THEN 'พบ' ELSE 'ไม่พบ' END    AS `พบรหัส O60.1`
FROM ipt i
WHERE i.dchdate BETWEEN @start_date AND @end_date
  -- AND i.ward = '00'      -- [ปรับตามโรงพยาบาล] (ทางเลือก) ให้ตรงกับที่เลือกใน Query 1
  AND EXISTS (
          SELECT 1
          FROM iptdiag dx1
          WHERE dx1.an = i.an
            AND REPLACE(dx1.icd10, '.', '') REGEXP '^O8[0-4]'
      )
ORDER BY i.dchdate, i.an;

-- ============================================================
-- 3) Query ตรวจสอบไขว้ด้วยรหัสทารก P07 (ทางเลือกเพื่อตรวจสอบไขว้)
-- ============================================================
-- นับ admission ของทารกแรกเกิดในช่วงเวลาเดียวกัน ที่มีรหัส prematurity:
--   P07.2 : ทารกอายุครรภ์น้อยกว่า 32 สัปดาห์
--   P07.3 : ทารกอายุครรภ์ 32 ถึงก่อน 37 สัปดาห์
-- ข้อควรระวังในการแปลผล:
--   1) query นี้นับ "ทารก" ไม่ใช่ "แม่" กรณีครรภ์แฝดตัวเลขจะมากกว่า Query 1
--   2) ขึ้นกับความครบถ้วนของการลงรหัสฝั่งทารกแรกเกิด
--   ตัวเลขจึงไม่จำเป็นต้องเท่ากับตัวตั้งของ Query 1 ใช้เพื่อดูว่าไปในทิศทางเดียวกันหรือไม่
-- ใช้ dchdate เป็นฐานเวลาเดียวกับ Query 1 เพื่อให้เทียบช่วงเวลากันได้

SELECT
    COUNT(*)                       AS `จำนวนทารกที่มีรหัส P07.2 หรือ P07.3`,
    IFNULL(SUM(t.p072_flag), 0)    AS `P07.2 (น้อยกว่า 32 สัปดาห์)`,
    IFNULL(SUM(t.p073_flag), 0)    AS `P07.3 (32 ถึงก่อน 37 สัปดาห์)`
FROM (
    SELECT
        i.an,
        MAX(CASE WHEN REPLACE(dx.icd10, '.', '') LIKE 'P072%' THEN 1 ELSE 0 END) AS p072_flag,
        MAX(CASE WHEN REPLACE(dx.icd10, '.', '') LIKE 'P073%' THEN 1 ELSE 0 END) AS p073_flag
    FROM ipt i
        JOIN iptdiag dx ON dx.an = i.an
    WHERE i.dchdate BETWEEN @start_date AND @end_date
      AND (
              REPLACE(dx.icd10, '.', '') LIKE 'P072%'
           OR REPLACE(dx.icd10, '.', '') LIKE 'P073%'
          )
    GROUP BY i.an   -- หนึ่งทารกหนึ่ง admission นับครั้งเดียว แม้มีหลายรหัส
) t;
