--               query นี้ประมาณค่าด้วยรหัส ICD-10 (การคลอด O80-O84 และคลอดก่อนกำหนด O60.1)
--               นิยามทางการของ HDC อาจต่างในรายละเอียด ดู README.md ในโฟลเดอร์เดียวกัน
